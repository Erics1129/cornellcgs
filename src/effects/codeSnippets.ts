export const CFR_UPDATE: string[] = [
  '// CFR — regret-matched strategy, one traversal update',
  'function cfr(n: Node, p0: number, p1: number): number {',
  '  if (n.terminal) return n.payoff()',
  '  const strat = regretMatch(n.regret)',
  '  const util = new Array<number>(n.actions).fill(0)',
  '  let nodeUtil = 0',
  '  for (let a = 0; a < n.actions; a++) {',
  '    util[a] = -cfr(n.next(a), p1, p0 * strat[a])',
  '    nodeUtil += strat[a] * util[a]',
  '  }',
  '  for (let a = 0; a < n.actions; a++) {',
  '    const regret = util[a] - nodeUtil',
  '    n.regret[a] += p1 * regret // weight by opp reach',
  '    n.stratSum[a] += p0 * strat[a]',
  '  }',
  '  return nodeUtil',
  '}',
  '',
  'function regretMatch(reg: number[]): number[] {',
  '  const pos = reg.map((r) => Math.max(r, 0))',
  '  const sum = pos.reduce((s, r) => s + r, 0)',
  '  if (sum <= 0) return pos.map(() => 1 / pos.length)',
  '  return pos.map((r) => r / sum) // play positive regret',
  '}',
]

export const POT_EQUITY: string[] = [
  '// Pot equity by Monte Carlo — deal the unseen, count wins',
  'function potEquity(hole: Card[], board: Card[], n = 2e4) {',
  '  const seen = new Set([...hole, ...board].map(key))',
  '  const deck = DECK.filter((c) => !seen.has(key(c)))',
  '  let win = 0',
  '  let tie = 0',
  '  for (let t = 0; t < n; t++) {',
  '    shuffle(deck)',
  '    const vill = deck.slice(0, 2)',
  '    const need = 5 - board.length',
  '    const run = board.concat(deck.slice(2, 2 + need))',
  '    const cmp = compare(best7(hole, run), best7(vill, run))',
  '    if (cmp > 0) win++',
  '    else if (cmp === 0) tie++',
  '  }',
  '  return (win + tie / 2) / n // share of the pot',
  '}',
  '',
  'function shuffle<T>(a: T[]) {',
  '  for (let i = a.length - 1; i > 0; i--) {',
  '    const j = Math.floor(Math.random() * (i + 1))',
  '    ;[a[i], a[j]] = [a[j], a[i]]',
  '  }',
  '}',
]

