  '// 5-card evaluator — [category, ...tiebreaks], higher wins',
  "const RANKS = '23456789TJQKA'",
  'type Card = { r: number; s: number }',
  '',
  'function parse(c: string): Card {',
  '  const r = RANKS.indexOf(c[0]) + 2',
