  '}',
  '',
  'function evaluate5(cs: Card[]): number[] {',
  '  const rs = cs.map((c) => c.r).sort((a, b) => b - a)',
  '  const flush = cs.every((c) => c.s === cs[0].s)',
  "  const wheel = rs.join() === '14,5,4,3,2'",
  '  const run = rs.every((r, i) => !i || r === rs[i - 1] - 1)',
  '  const straight = run || wheel',
  '  const hi = wheel ? 5 : rs[0]',
  '  if (straight && flush) return [8, hi]',
  '  const seen = new Map<number, number>()',
  '  for (const r of rs) seen.set(r, (seen.get(r) ?? 0) + 1)',
  '  const groups = [...seen.entries()]',
  '    .sort((a, b) => b[1] - a[1] || b[0] - a[0])',
  '    .map(([r]) => r)',
  "  const shape = [...seen.values()].sort().reverse().join('')",
