// Low-quality image placeholders for the World photographs: each photo at 48 px wide, blurred, as a WebP data URI.
// They are written into src/lib/earthJourney.ts (between the lqip markers) and shown as the figure's background,
// so a cold teleport into World shows a blurred photo at once instead of a dark box.
// usage: node scripts/cinema/lqip.mjs [width=48] [quality=0.5]
import fs from 'node:fs'
import path from 'node:path'
import { ROOT, assetPage } from './lib-assets.mjs'
const [width = '48', quality = '0.5'] = process.argv.slice(2)
const file = path.join(ROOT, 'src/lib/earthJourney.ts')
const source = fs.readFileSync(file, 'utf8')
const credits = fs.readFileSync(path.join(ROOT, 'public/assets/earth-journey/journey-v2-credits.json'), 'utf8')
const names = [...new Set([...source.matchAll(/image: '([^']+\.webp)'/g)].map(m => m[1]).concat([...credits.matchAll(/earth-journey\/([^"]+\.webp)/g)].map(m => m[1])))]
const { browser, page } = await assetPage()
const out = {}
for (const name of names) {
  out[name] = await page.evaluate(async ({ name, width, quality }) => {
    const bmp = await createImageBitmap(await (await fetch(`/assets/earth-journey/${name}`)).blob())
    const w = width, h = Math.round(width * bmp.height / bmp.width)
    const c = document.createElement('canvas'); c.width = w; c.height = h
    const x = c.getContext('2d'); x.imageSmoothingQuality = 'high'
    // a small blur before encoding removes the blocks a 48 px image would show when stretched over a screen
    x.filter = 'blur(1.2px)'; x.drawImage(bmp, -2, -2, w + 4, h + 4)
    return c.toDataURL('image/webp', quality)
  }, { name, width: +width, quality: +quality })
  console.log(name, `${(out[name].length / 1024).toFixed(1)} kB as a data URI`)
}
await browser.close()
const block = `// lqip:start (generated by scripts/cinema/lqip.mjs; do not edit by hand)\nexport const EARTH_LQIP: Record<string, string> = {\n${names.map(n => `  '${n}': '${out[n]}',`).join('\n')}\n}\n// lqip:end`
const next = /\/\/ lqip:start[\s\S]*\/\/ lqip:end/.test(source) ? source.replace(/\/\/ lqip:start[\s\S]*\/\/ lqip:end/, block) : `${source.trimEnd()}\n\n${block}\n`
fs.writeFileSync(file, next)
console.log('wrote', names.length, 'placeholders into src/lib/earthJourney.ts')
